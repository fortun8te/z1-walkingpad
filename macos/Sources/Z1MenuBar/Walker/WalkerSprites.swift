/// The walker's frames, as literal dot grids.
///
/// Every frame is 22 cells wide and 26 tall, strict side view, facing right.
/// `0` is empty, `1` is a dither dot (drawn at reduced alpha), `2` is a solid
/// dot. The grids are hand-authored, not generated from joint angles -- two
/// earlier attempts drove the figure from a rig and the silhouettes never read
/// at this size, because at 22x26 there are not enough cells for an angle to
/// land where you meant it.
///
/// The whole set shares ONE canonical skeleton, and it does not vary by pose:
///
///     row  0...4   head        cols  9...13  (nose pushes to 14 on rows 2-3)
///     row  5       neck        cols 10...11
///     row  6...9   chest       cols  8...13  (shoulders one cell FORWARD)
///     row 10...14  belly/hip   cols  8...12  (hips one cell BACK -> the lean)
///     row 15...25  legs
///     shoulder joint           (11, 7)
///     hip joint                (10, 14)
///     ground                   row 25
///
/// Depth is carried by ink, not by outline: the NEAR arm and leg are solid and
/// the FAR ones are dither. At 1-bit there is no tone to separate two
/// overlapping legs in a strict side view, so the dither is the tone. The near
/// limb is always the same physical leg -- across the cycle the poses swap, the
/// ink never does, because a figure whose solid leg alternates reads as turning
/// round rather than walking.
///
/// The dithered edge is subtractive: the outermost ring of the body is demoted
/// from solid to dither on a checkerboard anchored to the grid (`(col + row) %
/// 2`), never to the body. A cell that dithers in one frame dithers in every
/// frame it appears in, so the rim cannot crawl or flash as he moves.
